#!/usr/bin/env python3
"""Build var/words.tsv (word, kind, zipf) from wordfreq plus the curated lists in var/dictionary/.

    pip install wordfreq
    python3 bin/build-dictionary.py && php bin/backfill.php

Kinds, in order of precedence: extra.txt as tagged, tech, place, common (English), fr (French), name.
Frequencies are wordfreq Zipf values (log10 occurrences per billion words; ~7 = "the", ~3 = rare).
Shorter words need a higher frequency to qualify, since short fragments match inside many unrelated names.
Word list data: wordfreq (https://github.com/rspeer/wordfreq), CC BY-SA 4.0.
"""
import os
import re
import unicodedata

from wordfreq import top_n_list, zipf_frequency

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'var', 'dictionary')
WORD = re.compile(r'^[a-z]+$')

# Minimum Zipf frequency by word length (anything longer uses the last value).
EN_MIN = {3: 4.3, 4: 3.4, 5: 3.0, 6: 2.7}
FR_MIN = {4: 4.4, 5: 4.1, 6: 3.9, 7: 3.7}
NAME_MIN = 2.8


def need(table, length):
    return table.get(length, table[max(table)]) if length >= min(table) else None


def ascii_fold(word):
    return unicodedata.normalize('NFKD', word).encode('ascii', 'ignore').decode()


def read_list(name):
    with open(os.path.join(SRC, name), encoding='utf-8') as f:
        return [line.strip().lower() for line in f if line.strip() and not line.startswith('#')]


def main():
    blocked = set(read_list('blocklist.txt'))
    words = {}

    def add(word, kind, zipf):
        if WORD.match(word) and word not in blocked and word not in words:
            words[word] = (kind, zipf)

    for line in read_list('extra.txt'):
        word, kind = line.split('\t')
        add(word, kind, zipf_frequency(word, 'fr' if 'fr' == kind else 'en'))
    for word in read_list('tech.txt'):
        add(word, 'tech', zipf_frequency(word, 'en'))
    for word in read_list('places-ca.txt'):
        add(word, 'place', zipf_frequency(word, 'en'))

    for word in top_n_list('en', 250000):
        threshold = need(EN_MIN, len(word))
        zipf = zipf_frequency(word, 'en')
        if threshold is not None and zipf >= threshold:
            add(word, 'common', zipf)

    for word in top_n_list('fr', 60000):
        folded = ascii_fold(word)
        threshold = need(FR_MIN, len(folded))
        zipf = zipf_frequency(word, 'fr')
        if threshold is not None and zipf >= threshold:
            add(folded, 'fr', zipf)

    # Proper nouns from the old Hunspell list that aren't also ordinary words.
    with open(os.path.join(SRC, 'en_CA.dic'), encoding='utf-8') as f:
        lines = [line.strip() for line in f]
    lower = {line for line in lines if line[:1].islower()}
    for line in lines:
        word = line.lower()
        if line[:1].isupper() and word not in lower and len(word) >= 4:
            zipf = zipf_frequency(word, 'en')
            if zipf >= NAME_MIN:
                add(word, 'name', zipf)

    with open(os.path.join(ROOT, 'var', 'words.tsv'), 'w', encoding='utf-8') as f:
        f.write('# word\tkind\tzipf — generated by bin/build-dictionary.py\n')
        for word, (kind, zipf) in sorted(words.items()):
            f.write(f'{word}\t{kind}\t{zipf:.2f}\n')

    counts = {}
    for kind, _ in words.values():
        counts[kind] = counts.get(kind, 0) + 1
    print(len(words), 'words', counts)


if __name__ == '__main__':
    main()
